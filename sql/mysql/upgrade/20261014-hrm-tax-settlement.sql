CREATE TABLE IF NOT EXISTS hrm_payroll_tax_settlement (
 id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY,
 filing_id bigint NULL,
 entity_id bigint NULL,
 employee_id bigint NULL,
 profile_id bigint NULL,
 year int NULL,
 month int NULL,
 mode varchar(32) NULL,
 kind varchar(32) NULL,
 amount decimal(20,2) NULL,
 taxpayer_key varchar(64) NULL,
 tax_registration_number varchar(1000) NULL,
 employee_acknowledgement varchar(1000) NULL,
 evidence varchar(1000) NULL,
 reason varchar(1000) NULL,
 status varchar(32) NULL,
 submitted_by bigint NULL,
 reviewed_by bigint NULL,
 review_reason varchar(1000) NULL,
 reviewed_time datetime NULL,
 value_date date NULL,
 bank_reference varchar(100) NULL,
 bank_evidence varchar(1000) NULL,
 confirmed_by bigint NULL,
 confirmed_time datetime NULL,
 request_key varchar(100) NULL,
 request_snapshot LONGTEXT NULL,
 authority_snapshot LONGTEXT NULL,
 creator varchar(64) DEFAULT '',
 create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updater varchar(64) DEFAULT '',
 update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted bit NOT NULL DEFAULT FALSE,
 tenant_id bigint NOT NULL DEFAULT 0,
 UNIQUE KEY uk_tax_settlement_request(tenant_id,request_key),
 UNIQUE KEY uk_tax_settlement_bank(tenant_id,bank_reference)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS hrm_payroll_tax_settlement_event (
 id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY,
 settlement_id bigint NULL,
 actor_id bigint NULL,
 action varchar(32) NULL,
 reason varchar(1000) NULL,
 snapshot LONGTEXT NULL,
 creator varchar(64) DEFAULT '',
 create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updater varchar(64) DEFAULT '',
 update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted bit NOT NULL DEFAULT FALSE,
 tenant_id bigint NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
