SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS hrm_payroll_tax_correction (
 id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY,
 entity_id bigint NULL,
 employee_id bigint NULL,
 payment_id bigint NULL,
 run_id bigint NULL,
 prior_correction_id bigint NULL,
 version int NULL,
 policy_id bigint NULL,
 policy_version int NULL,
 profile_id bigint NULL,
 profile_version int NULL,
 value_date date NULL,
 tax_registration_number varchar(1000) NULL,
 taxpayer_key varchar(64) NULL,
 source_digest varchar(64) NULL,
 official_reference varchar(100) NULL,
 evidence varchar(1000) NULL,
 reason varchar(1000) NULL,
 income decimal(20,2) NULL,
 social_deduction decimal(20,2) NULL,
 basic_deduction decimal(20,2) NULL,
 actual_salary_withheld decimal(20,2) NULL,
 separate_bonus_income decimal(20,2) NULL,
 actual_bonus_withheld decimal(20,2) NULL,
 status varchar(32) NULL,
 submitted_by bigint NULL,
 approved_by bigint NULL,
 review_opinion varchar(1000) NULL,
 approved_time datetime NULL,
 request_key varchar(100) NULL,
 request_snapshot LONGTEXT NULL,
 original_snapshot LONGTEXT NULL,
 creator varchar(64) DEFAULT '',
 create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updater varchar(64) DEFAULT '',
 update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted bit NOT NULL DEFAULT FALSE,
 tenant_id bigint NOT NULL DEFAULT 0,
 active_payment_id bigint GENERATED ALWAYS AS (CASE WHEN deleted=b'0' AND status='APPROVED' THEN payment_id ELSE NULL END) STORED,
 UNIQUE KEY uk_tax_correction_request(tenant_id,request_key),
 UNIQUE KEY uk_tax_correction_version(tenant_id,payment_id,version),
 UNIQUE KEY uk_tax_correction_active(tenant_id,active_payment_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
